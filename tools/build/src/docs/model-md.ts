import type { Model } from '@uio/engine';
import { mdText } from '../markdown.ts';

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** The GitHub heading anchor of a scheme section: its id is already lowercase, digits and hyphens. */
const anchorOf = (id: string): string => id;

/**
 * docs/model.md (D-12): human-readable documentation of every scheme, generated from the
 * normalised model. `gapsText` is the text of docs/gaps.md, which the sections link into.
 */
export function renderModelMd(model: Model, _gapsText: string): string {
  const ids = Object.keys(model.schemes).sort(compare);
  const lines = [
    '# Model documentation',
    '',
    `This file is generated by \`npm run build:docs\` from the model (contract ${model.contract}, model version ${mdText(model.model_version)}); do not edit it by hand. CI fails when it is stale. It is published under CC-BY-4.0 (\`LICENSE-model\`).`,
    '',
    ...ids.map((id) => `- [${id}](#${anchorOf(id)})`),
  ];
  for (const id of ids) {
    const scheme = model.schemes[id];
    if (scheme === undefined) continue;
    lines.push('', `## ${id}`, '', `English: ${mdText(scheme.label.en)}`);
    lines.push(`Dutch: ${scheme.label.nl === undefined ? 'none' : mdText(scheme.label.nl)}`);
  }
  return `${lines.join('\n')}\n`;
}
